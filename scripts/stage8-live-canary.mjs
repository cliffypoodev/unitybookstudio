#!/usr/bin/env node

import { writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import {
  runSceneExecutionLiveCanary,
  SCENE_EXECUTION_LIVE_CANARY_FEATURE,
} from '../src/lib/sceneExecutionLiveCanary.js';
import {
  SCENE_CONTEXT_COMPOSER_FEATURE,
  SCENE_EXECUTION_CANARY_COMPARISON_FEATURE,
  SCENE_EXECUTION_CANARY_TRIAL_FEATURE,
  SCENE_EXECUTION_PROMPT_CANARY_FEATURE,
  SCENE_EXECUTION_SHADOW_FEATURE,
} from '../src/lib/generationContext.js';

function usage() {
  console.log(`Usage:
  node scripts/stage8-live-canary.mjs [options]

Options:
  --endpoint URL     llama.cpp OpenAI-compatible base URL
                     (default: http://127.0.0.1:8080/v1)
  --model ID         Exact loaded model ID. Optional when llama.cpp exposes
                     one model or qwen3.6-35b-uncensored.
  --run-id ID        Opaque run ID. A timestamped ID is generated by default.
  --help             Show this help.

This is a test-only paired comparison. It contacts only a loopback endpoint,
makes exactly two matched model calls, never changes a UBS project, and keeps
raw prompts/prose in a private temporary review file.`);
}

function parseArgs(argv) {
  const parsed = {};
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === '--help') {
      parsed.help = true;
      continue;
    }
    if (!['--endpoint', '--model', '--run-id'].includes(arg)) {
      throw new Error(`Unknown option: ${arg}`);
    }
    const value = argv[index + 1];
    if (!value || value.startsWith('--')) {
      throw new Error(`Missing value for ${arg}`);
    }
    index += 1;
    if (arg === '--endpoint') parsed.endpoint = value;
    if (arg === '--model') parsed.model = value;
    if (arg === '--run-id') parsed.runId = value;
  }
  return parsed;
}

function defaultRunId() {
  return `live-ch01-s02-${new Date()
    .toISOString()
    .replace(/\D/g, '')
    .slice(0, 14)}`;
}

try {
  const options = parseArgs(process.argv.slice(2));
  if (options.help) {
    usage();
    process.exit(0);
  }

  const flags = {
    [SCENE_CONTEXT_COMPOSER_FEATURE.key]: true,
    [SCENE_EXECUTION_SHADOW_FEATURE.key]: true,
    [SCENE_EXECUTION_PROMPT_CANARY_FEATURE.key]: true,
    [SCENE_EXECUTION_CANARY_TRIAL_FEATURE.key]: true,
    [SCENE_EXECUTION_CANARY_COMPARISON_FEATURE.key]: true,
    [SCENE_EXECUTION_LIVE_CANARY_FEATURE.key]: true,
  };
  const runId = options.runId || defaultRunId();
  const integration = {
    flags,
    mode: 'test-only-local-llama-paired-evaluation',
    runId,
    ...(options.endpoint ? { endpoint: options.endpoint } : {}),
    ...(options.model ? { model: options.model } : {}),
  };

  console.log('Stage 8: verifying the local llama.cpp model and running one matched pair...');
  const result = await runSceneExecutionLiveCanary({
    integration,
    fetchImpl: globalThis.fetch,
  });
  const outputPath = join(tmpdir(), `ubs-stage8-${runId}.json`);
  await writeFile(
    outputPath,
    `${JSON.stringify(
      {
        stage: 8,
        attestation: result.attestation,
        comparison: result.comparison,
        local_review: result.localReview,
      },
      null,
      2
    )}\n`,
    { encoding: 'utf8', mode: 0o600, flag: 'wx' }
  );

  console.log('\nSTAGE 8 CONTENT-FREE ATTESTATION');
  console.log(JSON.stringify(result.attestation, null, 2));
  console.log(`\nPrivate side-by-side review file:\n${outputPath}`);
  console.log(
    '\nBroader rollout remains on hold. Return the attestation and review file output for human quality evaluation.'
  );
} catch (error) {
  console.error('\nSTAGE 8 STOPPED SAFELY');
  console.error(`${error?.code || error?.name || 'ERROR'}: ${error?.message || error}`);
  if (Array.isArray(error?.issues)) {
    for (const issue of error.issues) console.error(`- ${issue}`);
  }
  process.exitCode = 1;
}
