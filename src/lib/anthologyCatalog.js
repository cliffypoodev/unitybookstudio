/**
 * Import all anthology catalog entries into PromptCatalog entity.
 * Call this once. Checks for duplicates by title before creating.
 */
export async function importAnthologyCatalog(base44, onProgress) {
  const existing = await base44.entities.PromptCatalog.list('-created_date', 2000);
  const existingTitles = new Set(existing.map(p => p.title?.toLowerCase()));
  
  let created = 0;
  let skipped = 0;
  
  for (let i = 0; i < ANTHOLOGY_CATALOG.length; i++) {
    const rec = ANTHOLOGY_CATALOG[i];
    if (existingTitles.has(rec.title?.toLowerCase())) {
      skipped++;
      continue;
    }
    try {
      await base44.entities.PromptCatalog.create(rec);
      created++;
    } catch (e) {
      console.warn('[CATALOG] Failed to create:', rec.title, e.message);
    }
    if (onProgress) onProgress(`Importing ${i + 1}/${ANTHOLOGY_CATALOG.length} (${created} created, ${skipped} skipped)`);
  }
  
  return { created, skipped, total: ANTHOLOGY_CATALOG.length };
}